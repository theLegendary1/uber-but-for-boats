import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, cpSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

test('real commits bump once, keep lockfile aligned, and protect unstaged files', (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'dockwash-version-hook-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git('init', '-q');
  git('config', 'user.name', 'Release Test');
  git('config', 'user.email', 'release@example.test');
  git('config', 'commit.gpgsign', 'false');
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: 'test', type: 'module', version: '0.1.0' }));
  writeFileSync(join(dir, 'package-lock.json'), JSON.stringify({ version: '0.1.0', packages: { '': { version: '0.1.0' } } }));
  git('add', '.');
  git('commit', '-qm', 'Initial import');
  mkdirSync(join(dir, 'scripts'));
  for (const file of ['version-commit.js', 'versioning.js', 'flavor-commit.js', 'check-version-files.js']) cpSync(resolve('scripts', file), join(dir, 'scripts', file));
  git('config', 'core.hooksPath', resolve('.githooks'));
  writeFileSync(join(dir, 'feature.txt'), 'A new feature');
  git('add', '.');
  git('commit', '-qm', 'feat: schedule the crew');
  assert.equal(JSON.parse(git('show', 'HEAD:package.json')).version, '0.2.0');
  assert.equal(JSON.parse(git('show', 'HEAD:package-lock.json')).packages[''].version, '0.2.0');
  assert.match(git('show', '-s', '--format=%s'), /\[Dale:/);
  assert.match(git('show', 'HEAD:CHANGELOG.md'), /## \[0.2.0\]/);
  writeFileSync(join(dir, 'feature.txt'), 'Fix the feature');
  git('add', 'feature.txt');
  const pkgPath = join(dir, 'package.json');
  const original = readFileSync(pkgPath, 'utf8');
  writeFileSync(pkgPath, original + '\n');
  assert.throws(() => git('commit', '-qm', 'fix: adjust the crew'), /unstaged edits/);
  assert.equal(readFileSync(pkgPath, 'utf8'), original + '\n');
  writeFileSync(pkgPath, original);
  git('commit', '-qm', 'fix: adjust the crew');
  assert.equal(JSON.parse(git('show', 'HEAD:package.json')).version, '0.2.1');
  assert.equal(git('status', '--porcelain'), '');
});
